import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:asken_pos/app/core/features/checkout/data/AppProviders.dart';
import 'package:asken_pos/app/core/features/owner/application/CloudSyncSettingsNotifier.dart';
import 'package:asken_pos/app/core/features/owner/application/GoogleDriveConnectionNotifier.dart';
import 'package:asken_pos/app/core/database/AppDatabase.dart';

class CloudSyncSettingsPage extends ConsumerWidget {
  const CloudSyncSettingsPage({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final SettingsState = ref.watch(CloudSyncSettingsProvider);
    final ConnectionState = ref.watch(GoogleDriveConnectionProvider);
    final IsConnecting = ConnectionState.isLoading;

    return Scaffold(
      appBar: AppBar(title: const Text('Cloud Folder Setup')),
      body: Center(
        child: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 560),
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(24),
            child: SettingsState.when(
              loading: () => const Center(child: CircularProgressIndicator()),
              error: (Error, StackTrace) => _ErrorState(
                ErrorMessage: Error.toString(),
                OnRetry: () => ref.invalidate(CloudSyncSettingsProvider),
              ),
              data: (Settings) => _SettingsContent(
                Settings: Settings,
                IsConnecting: IsConnecting,
                OnProvision: () async {
                  await ref
                      .read(GoogleDriveConnectionProvider.notifier)
                      .Connect();
                  ref.invalidate(CloudSyncSettingsProvider);
                },
              ),
            ),
          ),
        ),
      ),
    );
  }
}

class _SettingsContent extends StatelessWidget {
  final CloudSyncSetting Settings;
  final bool IsConnecting;
  final Future<void> Function() OnProvision;

  const _SettingsContent({
    required this.Settings,
    required this.IsConnecting,
    required this.OnProvision,
  });

  @override
  Widget build(BuildContext context) {
    final IsProvisioned =
        Settings.IsAppOwned &&
        Settings.ProvisioningStatus == 'provisioned';
    final StatusLabel = IsProvisioned
        ? 'App-owned folders are ready.'
        : Settings.ProvisioningStatus == 'repair_required'
        ? 'Folder setup needs to be repaired.'
        : 'Folders have not been created by the app yet.';

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Text(
          'Business cloud storage',
          style: Theme.of(context).textTheme.headlineSmall,
        ),
        const SizedBox(height: 8),
        const Text(
          'The app creates and owns its transaction and EOD folders. Folder IDs are generated by Google Drive and are not entered manually.',
        ),
        const SizedBox(height: 24),
        Card(
          child: Padding(
            padding: const EdgeInsets.all(16),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  StatusLabel,
                  style: Theme.of(context).textTheme.titleMedium,
                ),
                const SizedBox(height: 8),
                Text('Provisioning status: ${Settings.ProvisioningStatus}'),
                if (Settings.FolderOwnerEmail != null) ...[
                  const SizedBox(height: 4),
                  Text('Google account: ${Settings.FolderOwnerEmail}'),
                ],
                if (Settings.LastValidatedAt != null) ...[
                  const SizedBox(height: 4),
                  Text('Last validated: ${Settings.LastValidatedAt}'),
                ],
              ],
            ),
          ),
        ),
        if (IsProvisioned) ...[
          const SizedBox(height: 16),
          _FolderIDCard(
            Label: 'Transaction Logs folder ID',
            FolderID: Settings.TransactionLogsFolderID,
          ),
          const SizedBox(height: 12),
          _FolderIDCard(
            Label: 'EOD Logs folder ID',
            FolderID: Settings.EodLogsFolderID,
          ),
        ],
        const SizedBox(height: 24),
        FilledButton.icon(
          onPressed: IsConnecting ? null : OnProvision,
          icon: const Icon(Icons.create_new_folder_outlined),
          label: Text(
            IsConnecting
                ? 'Creating folders...'
                : IsProvisioned
                ? 'Reconnect and Validate Folders'
                : 'Connect and Create Folders',
          ),
        ),
      ],
    );
  }
}

class _FolderIDCard extends StatelessWidget {
  final String Label;
  final String FolderID;

  const _FolderIDCard({required this.Label, required this.FolderID});

  @override
  Widget build(BuildContext context) {
    return Card(
      child: ListTile(
        title: Text(Label),
        subtitle: SelectableText(FolderID),
        leading: const Icon(Icons.folder_outlined),
      ),
    );
  }
}

class _ErrorState extends StatelessWidget {
  final String ErrorMessage;
  final VoidCallback OnRetry;

  const _ErrorState({required this.ErrorMessage, required this.OnRetry});

  @override
  Widget build(BuildContext context) {
    return Column(
      children: [
        Text(ErrorMessage),
        const SizedBox(height: 16),
        OutlinedButton(onPressed: OnRetry, child: const Text('Retry')),
      ],
    );
  }
}
